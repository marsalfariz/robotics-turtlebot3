#!/usr/bin/env python3
"""Generate the Gazebo Fortress world with a black oval (stadium-shaped) line track.

The track = 2 straight lines + 2 half circles, built from many thin flat black
boxes laid end to end. Boxes are 1 mm tall and have no collision, so the robot
drives over them as if the line were painted on the floor.

Usage (from the package folder):
    python3 scripts/generate_track.py              # writes worlds/line_track.sdf
    python3 scripts/generate_track.py --radius 1.2 --straight 3.0
"""
import argparse
import math
import os


def stadium_points(straight, radius, step):
    """Return a list of (x, y) points around a stadium shape centred at the origin."""
    pts = []
    half = straight / 2.0
    n_line = max(1, int(round(straight / step)))
    n_arc = max(8, int(round(math.pi * radius / step)))
    # bottom straight, left -> right (y = -radius)
    for i in range(n_line):
        pts.append((-half + straight * i / n_line, -radius))
    # right half circle, bottom -> top
    for i in range(n_arc):
        a = -math.pi / 2 + math.pi * i / n_arc
        pts.append((half + radius * math.cos(a), radius * math.sin(a)))
    # top straight, right -> left (y = +radius)
    for i in range(n_line):
        pts.append((half - straight * i / n_line, radius))
    # left half circle, top -> bottom
    for i in range(n_arc):
        a = math.pi / 2 + math.pi * i / n_arc
        pts.append((-half + radius * math.cos(a), radius * math.sin(a)))
    return pts


def segment_xml(idx, p0, p1, width, thickness):
    x0, y0 = p0
    x1, y1 = p1
    length = math.hypot(x1 - x0, y1 - y0) + width * 0.5  # small overlap hides gaps on curves
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    yaw = math.atan2(y1 - y0, x1 - x0)
    return f"""      <visual name="seg_{idx:03d}">
        <pose>{cx:.4f} {cy:.4f} {thickness / 2:.4f} 0 0 {yaw:.4f}</pose>
        <geometry><box><size>{length:.4f} {width:.4f} {thickness:.4f}</size></box></geometry>
        <material>
          <ambient>0 0 0 1</ambient><diffuse>0 0 0 1</diffuse><specular>0 0 0 1</specular>
        </material>
      </visual>
"""


def build_world(straight, radius, width, step):
    thickness = 0.001
    pts = stadium_points(straight, radius, step)
    segs = ''.join(
        segment_xml(i, pts[i], pts[(i + 1) % len(pts)], width, thickness)
        for i in range(len(pts))
    )
    floor = 2 * (straight / 2 + radius) + 4.0  # floor bigger than the track
    return f"""<?xml version="1.0" ?>
<!-- GENERATED by scripts/generate_track.py: edit the script, not this file.
     Track: straight={straight} m, radius={radius} m, line width={width} m.
     Suggested robot start pose: x=0, y={-radius}, yaw=0 (on the bottom straight, facing +x). -->
<sdf version="1.8">
  <world name="line_track">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="ignition-gazebo-physics-system" name="ignition::gazebo::systems::Physics"/>
    <plugin filename="ignition-gazebo-user-commands-system" name="ignition::gazebo::systems::UserCommands"/>
    <plugin filename="ignition-gazebo-scene-broadcaster-system" name="ignition::gazebo::systems::SceneBroadcaster"/>
    <plugin filename="ignition-gazebo-sensors-system" name="ignition::gazebo::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>

    <scene>
      <ambient>0.8 0.8 0.8 1</ambient>
      <background>0.7 0.8 0.9 1</background>
      <shadows>false</shadows>
    </scene>

    <!-- Main light: sun from above (no shadows so the line stays clearly black on white) -->
    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>1 1 1 1</diffuse>
      <specular>0.1 0.1 0.1 1</specular>
      <direction>-0.2 0.1 -1</direction>
    </light>
    <!-- Fill light from the opposite side for even brightness -->
    <light type="directional" name="fill">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.4 0.4 0.4 1</diffuse>
      <specular>0 0 0 1</specular>
      <direction>0.2 -0.1 -1</direction>
    </light>

    <!-- White floor -->
    <model name="floor">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>{floor:.1f} {floor:.1f}</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>{floor:.1f} {floor:.1f}</size></plane></geometry>
          <material>
            <ambient>1 1 1 1</ambient><diffuse>1 1 1 1</diffuse><specular>0.1 0.1 0.1 1</specular>
          </material>
        </visual>
      </link>
    </model>

    <!-- Black line track: visuals only, no collision -->
    <model name="track">
      <static>true</static>
      <link name="link">
{segs}      </link>
    </model>
  </world>
</sdf>
"""


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    default_out = os.path.join(here, '..', 'worlds', 'line_track.sdf')
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--straight', type=float, default=3.0, help='length of each straight part [m]')
    ap.add_argument('--radius', type=float, default=1.2, help='radius of the curves [m]')
    ap.add_argument('--width', type=float, default=0.03, help='line width [m]')
    ap.add_argument('--step', type=float, default=0.05, help='segment length [m]')
    ap.add_argument('-o', '--output', default=default_out)
    args = ap.parse_args()

    xml = build_world(args.straight, args.radius, args.width, args.step)
    with open(args.output, 'w') as f:
        f.write(xml)
    print(f'Wrote {os.path.normpath(args.output)}')


if __name__ == '__main__':
    main()
